import assert from 'node:assert/strict';
import { applyLivestockAction as act } from '../shared/livestockActions.js';
import { FARM_CONFIG } from '../shared/farmConfig.js';
const player = () => ({ progress: { coins: 5000, xp: 0, stats: { animalsFed: 0 }, inventory: {}, barnLevel: 1 }, livestock: [] });
const p = player(); let serial = 0;
for (const species of Object.keys(FARM_CONFIG.animals)) {
  assert.throws(() => act(p, 'buy_animal', { species }), /xây chuồng/);
  act(p, 'build_pen', { species });
  act(p, 'buy_animal', { species }, 100, () => String(++serial));
}
act(p, 'feed_animals', {}, 100);
const times = p.livestock.map(a => a.productReadyAt);
assert.throws(() => act(p, 'feed_animals', {}, 200), /thu sản phẩm/);
assert.deepEqual(p.livestock.map(a => a.productReadyAt), times);
assert.throws(() => act(p, 'sell_animal', { id: '3' }, 101), /chưa trưởng/);
act(p, 'collect_animals', {}, 7300000);
assert.deepEqual(p.progress.inventory, { egg: 4, duckEgg: 4, milk: 4, wool: 4 });
const coins = p.progress.coins;
act(p, 'sell_animal', { id: '3' }, 7300000);
assert.equal(p.progress.coins, coins + FARM_CONFIG.products.maturePig.sellPrice);
assert.throws(() => act(p, 'sell_animal', { id: '3' }, 7300000));
for (let i=0;i<2;i++) act(p, 'buy_animal', { species:'chicken' }, 100, () => String(++serial));
assert.throws(() => act(p, 'buy_animal', { species:'chicken' }), /đầy/);
const poor = player(); poor.progress.coins = 0;
assert.throws(() => act(poor, 'build_pen', { species:'cow' }), /xu/);
assert.equal(poor.progress.animalPens, undefined);
console.log('PASS livestock: five species, pens, prices, capacity, preserved production, collect and pig sale');

const targeted=player();targeted.progress.animalPens={chicken:true,duck:true};
act(targeted,'buy_animal',{species:'chicken'},100,()=> 'a');
act(targeted,'buy_animal',{species:'chicken'},100,()=> 'b');
act(targeted,'buy_animal',{species:'duck'},100,()=> 'c');
const before=targeted.progress.coins;
act(targeted,'feed_animals',{id:'a'},1000);
assert.equal(targeted.progress.coins,before-FARM_CONFIG.animals.chicken.feedCost*4);
assert.equal(targeted.livestock.find(a=>a.id==='b').productReadyAt,0);
act(targeted,'feed_animals',{species:'duck'},1000);
assert.equal(targeted.livestock.find(a=>a.id==='b').productReadyAt,0);
assert.throws(()=>act(targeted,'feed_animals',{id:'someone-else'},1000),/không thuộc/);
assert.throws(()=>act(targeted,'feed_animals',{species:'dragon'},1000),/không hợp lệ/);
act(targeted,'collect_animals',{id:'a'},3000000);
assert.equal(targeted.progress.inventory.egg,4);
assert.equal(targeted.progress.inventory.duckEgg,undefined);
assert.ok(targeted.livestock.find(a=>a.id==='c').productReadyAt>0);
act(targeted,'collect_animals',{species:'duck'},3000000);
assert.equal(targeted.progress.inventory.duckEgg,4);
assert.equal(targeted.livestock.length,3);
console.log('PASS livestock targeted actions: per-animal and per-species feeding/collection, server prices and foreign-id rejection');
