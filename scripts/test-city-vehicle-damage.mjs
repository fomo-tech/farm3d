import assert from 'node:assert/strict';
import {applyCityAction,CITY_GARAGE} from '../shared/cityGameplay.js';
import {cityVehicleHealth,cityRepairCost} from '../shared/cityGarage.js';
import {cityActionAllowed} from '../shared/cityOnlyPolicy.js';
import {performAction} from '../server/GameStore.js';
import {stepCityDriving} from '../src/game/player/cityDriving.js';
const p={coins:500,xp:0,vehicle:'walk',ownedVehicles:['walk']},c={worldMode:'city',...CITY_GARAGE};
for(const throttle of [-1,0,1])assert.deepEqual(stepCityDriving(10,1,throttle,1,false,.05,0),{speed:0,yaw:1});
applyCityAction(p,'city_enter',{},c,10000);applyCityAction(p,'city_vehicle',{},c,10000);
assert.equal(cityActionAllowed('city_vehicle_impact'),false);
assert.ok((await performAction('not-a-real-account','city_vehicle_impact',{damage:999},c)).error);
assert.throws(()=>applyCityAction(p,'city_vehicle_impact',{},c,10000));
const impact=(time,speed=15)=>applyCityAction(p,'city_vehicle_impact',{}, {...c,trustedCityImpact:true,impactSpeed:speed},time);
impact(10000);assert.equal(cityVehicleHealth(p),77);impact(11000);assert.equal(cityVehicleHealth(p),77,'Contact cannot spam damage');
impact(14000,1);assert.equal(cityVehicleHealth(p),77,'Low speed contacts do not damage');
impact(14000,NaN);assert.equal(cityVehicleHealth(p),77);
p.city.contract={id:'south-delivery',startedAt:0};impact(15000,30);impact(18000,30);impact(21000,30);
assert.equal(cityVehicleHealth(p),0);assert.equal(p.city.contract,null);assert.equal(p.city.lastResult.status,'failed');
assert.equal(p.vehicle,'walk');assert.throws(()=>applyCityAction(p,'city_vehicle',{},c,22000));assert.throws(()=>applyCityAction(p,'city_respawn',{},c,23000));
applyCityAction(p,'city_respawn',{},c,26000);assert.throws(()=>applyCityAction(p,'city_vehicle',{},c,26001));
assert.throws(()=>applyCityAction(p,'city_garage_repair',{}, {...c,x:999},24000));
const cost=cityRepairCost(0);applyCityAction(p,'city_garage_repair',{},c,27000);assert.equal(p.coins,500-cost);assert.equal(cityVehicleHealth(p),100);
assert.throws(()=>applyCityAction(p,'city_garage_repair',{},c,25000));
applyCityAction(p,'city_vehicle',{},c,36000);impact(37000,30);
const saved=JSON.parse(JSON.stringify(p));assert.equal(cityVehicleHealth(saved),65);
assert.equal(saved.city.garage.health.roadster,65);
applyCityAction(p,'city_vehicle',{},c,28000);p.city.garage.health.roadster=0;p.coins=0;p.city.carPosition={x:200,z:0};
applyCityAction(p,'city_garage_recover',{},c,29000);assert.equal(p.coins,0);assert.equal(cityVehicleHealth(p),20);assert.deepEqual(p.city.carPosition,CITY_GARAGE);
applyCityAction(p,'city_vehicle',{},c,30000);assert.equal(p.vehicle,'convertible','Broke player is not permanently locked out of missions');
console.log('PASS damage/repair: server-only impact, speed/cooldown, wreck, mission failure, repair fee, save/reload and broke-player recovery');
