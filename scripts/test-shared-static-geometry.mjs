import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { MeshBuilder } from '@babylonjs/core/Meshes/meshBuilder.js';
import { installSharedStaticGeometry } from '../src/game/rendering/SharedStaticGeometry.js';
const engine = new NullEngine(), scene = new Scene(engine);
const pool = installSharedStaticGeometry(scene, { budgetMs: 100, batchSize: 1000 });
const a = MeshBuilder.CreateBox('house-wall-a', {}, scene);
const b = MeshBuilder.CreateBox('house-wall-b', {}, scene);
b.position.x = 10;
const different = MeshBuilder.CreateBox('house-wide', { width: 2 }, scene);
const dynamic = MeshBuilder.CreateBox('dynamic', { updatable: true }, scene);
const original = b.geometry;
await new Promise(resolve => setTimeout(resolve, 0));
pool.drain();
assert.equal(a.geometry, b.geometry);
assert.ok(original.isDisposed(), 'duplicate GPU and CPU buffers are released');
assert.notEqual(a.geometry, different.geometry);
assert.notEqual(a.geometry, dynamic.geometry);
assert.equal(b.position.x, 10);
a.dispose();
assert.equal(b.getTotalVertices(), 24, 'disposing a peer preserves shared geometry');
for (let i = 0; i < 200; i++) MeshBuilder.CreateBox(`wall-${i}`, {}, scene);
await new Promise(resolve => setTimeout(resolve, 0));
pool.drain();
assert.equal(scene.geometries.length, 3, 'repeated primitives remain bounded');
assert.equal(pool.getStats().saved, 201);
scene.dispose(); engine.dispose();
console.log('PASS shared rigid geometry, actual buffer disposal, independent transforms, mutable exclusion and peer lifetime');
