import assert from 'node:assert/strict';
import {applyCityAction,CITY_GARAGE,cityState} from '../shared/cityGameplay.js';
import {CITY_PAINT_PRICE} from '../shared/cityGarage.js';
const c={worldMode:'city',...CITY_GARAGE},p={coins:1200,xp:0,vehicle:'walk',ownedVehicles:['walk']};
const act=(a,payload={},context=c)=>applyCityAction(p,a,payload,context,10000);
act('city_enter');assert.deepEqual(cityState(p).garage.owned,['roadster']);
act('city_garage_buy',{id:'roadster-gt'});assert.equal(p.coins,300);
assert.throws(()=>act('city_garage_buy',{id:'roadster-gt'}));assert.equal(p.coins,300);
act('city_garage_select',{id:'roadster-gt'});assert.equal(p.city.garage.selected,'roadster-gt');
act('city_garage_paint',{color:'#d1c8b5'});assert.equal(p.coins,300-CITY_PAINT_PRICE);
assert.throws(()=>act('city_garage_paint',{color:'#d1c8b5'}));
assert.throws(()=>act('city_garage_paint',{color:'red'}));
assert.throws(()=>act('city_garage_select',{id:'roadster'}, {...c,x:999}));
assert.throws(()=>act('city_garage_select',{id:'roadster'}, {...c,wantedStars:1}));
act('city_vehicle');assert.throws(()=>act('city_garage_select',{id:'roadster'}));act('city_vehicle');
p.city.contract={id:'south-delivery',startedAt:1000};assert.throws(()=>act('city_garage_select',{id:'roadster'}));p.city.contract=null;
p.city.carPosition={x:200,z:0};assert.throws(()=>act('city_garage_select',{id:'roadster'}));
act('city_garage_recover');assert.deepEqual(p.city.carPosition,CITY_GARAGE);assert.equal(p.coins,165);
const restored=JSON.parse(JSON.stringify(p));assert.equal(cityState(restored).garage.selected,'roadster-gt');assert.equal(cityState(restored).garage.paints['roadster-gt'],'#d1c8b5');
const before=p.coins;p.coins=0;assert.throws(()=>act('city_garage_paint',{color:'#283238'}));assert.equal(p.coins,0);p.coins=before;
console.log('PASS garage: purchase once, ownership, select, paint cost/validation, recovery, reload, proximity, wanted, contract and driving locks');
