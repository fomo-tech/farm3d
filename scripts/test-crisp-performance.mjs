import assert from 'node:assert/strict';
import {AutoGraphicsController, calculateRenderDpr} from '../src/game/rendering/GraphicsSettings.js';
import {installNearbyShadows} from '../src/game/rendering/NearbyShadowCasters.js';
const controller = new AutoGraphicsController();
for (let i=0;i<900;i++) controller.sample(22);
assert.equal(controller.level,2,'45 FPS reduces effects in two sustained windows');
assert.equal(controller.scale,1);
assert.equal(calculateRenderDpr({quality:'auto',nativeDpr:2,width:1280,height:720,scale:.7}),2);
for (let i=0;i<1000;i++) controller.sample(18);
assert.equal(controller.level,2,'55 FPS does not oscillate into an expensive preset');
const map = {};
let budget=48;
const count=installNearbyShadows({getShadowMap:()=>map},()=>({x:0,y:0,z:0}),{maxCasters:()=>budget});
const meshes=Array.from({length:60},(_,i)=>({name:`caster-${i}`,position:{x:i/10,y:0,z:0}}));
assert.equal(map.getCustomRenderList(0,meshes).length,48);
budget=16;
assert.equal(map.getCustomRenderList(0,meshes).length,16,'Pressure updates the caster budget immediately');
assert.equal(count(),16);
budget=48;
assert.equal(map.getCustomRenderList(0,meshes).length,48,'Recovery restores the caster budget');
console.log('PASS: 60 FPS pressure thresholds, stable native pixels, hysteresis and adaptive shadow draw budget');
