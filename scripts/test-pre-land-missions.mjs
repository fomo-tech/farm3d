import assert from 'node:assert/strict';
import {preLandJourney, missionStats} from '../shared/preLandJourney.js';
import {normalizeMissions, dailyMissionList, claimMission, freshDailyMissions} from '../shared/missions.js';
import {normalizeFishingState} from '../shared/fishingConfig.js';
import {sellFishingCatch} from '../shared/fishingSales.js';
import {simulatePreLand} from './economy/preLandSimulation.js';
const now=Date.parse('2026-10-07T02:00:00Z');
const p={coins:180,xp:0,stats:{},onboarding:{completed:false},fishing:normalizeFishingState(),unlockedPlots:0};
p.missions=normalizeMissions(null,missionStats(p),now,{hasLand:false});
assert.equal(preLandJourney(p).id,'gear');
assert.equal(dailyMissionList(p.missions).length,3);
assert.equal(dailyMissionList(p.missions).reduce((n,m)=>n+m.coins,0),105);
assert.match(claimMission(p,'daily','daily-fish-3',now,{hasLand:false}),/cần câu/);
p.fishing.ownedRods=['rod_bamboo'];assert.equal(preLandJourney(p).id,'catch');
p.fishing.stats.totalCaught=6;assert.equal(preLandJourney(p).id,'sell');
assert.match(claimMission(p,'daily','daily-fish-3',now,{hasLand:false}),/bán cá/);
p.fishing.fish={carp:{count:3,totalWeight:4.5}};sellFishingCatch(p.fishing,'fishing_sell_all',{},now);
assert.equal(p.fishing.stats.totalSold,3);assert.equal(preLandJourney(p).id,'land');
for(const m of dailyMissionList(p.missions))assert.equal(claimMission(p,'daily',m.id,now,{hasLand:false}),null);
assert.equal(p.coins,285);assert.equal(p.xp,55);
assert.match(claimMission(p,'daily','daily-fish-3',now,{hasLand:false}),/đã được nhận/);
const sameDay=normalizeMissions(p.missions,missionStats(p),now,{hasLand:true});
assert.deepEqual(sameDay.daily,p.missions.daily,'buying land cannot reroll rewards');
const next=normalizeMissions(sameDay,missionStats(p),now+86400000,{hasLand:true});
assert.ok(dailyMissionList(next).every(m=>m.requirements.includes('land')));
const old=normalizeMissions({main:{claimed:['main-harvest-3']},daily:freshDailyMissions({planted:9},now)},missionStats(p),now,{hasLand:false});
assert.equal(old.daily.baseline.planted,9);assert.deepEqual(old.main.claimed,['main-harvest-3']);
const run=simulatePreLand({sessions:4,sessionMinutes:30});
assert.equal(run.cashflow['daily-mission'],210,'two sessions per day share a daily budget');
assert.equal(run.coins,Object.values(run.cashflow).reduce((a,b)=>a+b,0));
console.log('PASS: pre-land guide, daily unlocks/claims, 105 daily budget, stable assignment after purchase, migration and simulator conservation.');
