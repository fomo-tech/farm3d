import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { FARM_CONFIG, CROPS, validateFarmConfig, collectFarmProducts, farmBarnCapacity, farmBarnUpgradeCost, farmGrowthStage } from '../shared/farmConfig.js';
import { CROPS as CLIENT_CROPS, barnCapacity } from '../src/game/economy/GameProgress.js';
assert.equal(CLIENT_CROPS, CROPS);
assert.equal(CROPS.carrot.growMs, 60000, 'existing balance is preserved');
assert.equal(farmBarnCapacity(1), 20);
assert.equal(farmBarnUpgradeCost(3), 1050);
assert.deepEqual([0, .25, .75, 1].map(farmGrowthStage), [0, 1, 2, 3]);
assert.equal(barnCapacity({ barnLevel: 3 }), 60);
assert.ok(Object.isFrozen(FARM_CONFIG.animals.cow));
const bad = structuredClone(FARM_CONFIG);
bad.crops.carrot.growMs = -1;
assert.throws(() => validateFarmConfig(bad), /crops.carrot.growMs/);
const badProduct = structuredClone(FARM_CONFIG);
badProduct.animals.duck.product = 'missing';
assert.throws(() => validateFarmConfig(badProduct), /unknown product/);
const animals = Object.keys(FARM_CONFIG.animals).map(species => ({ species, productReadyAt: 100 }));
const result = collectFarmProducts(animals, 101);
assert.deepEqual(result.products, { egg: 1, duckEgg: 1, milk: 1, wool: 1 });
assert.equal(collectFarmProducts(result.livestock, 102).count, 0, 'cannot collect twice');
assert.equal(animals[0].productReadyAt, 100, 'capacity failure can leave original state intact');
assert.equal(collectFarmProducts(animals, 99).count, 0, 'early collection rejected');
const server = await readFile(new URL('../server/GameStore.js', import.meta.url), 'utf8');
assert.match(server, /from '..\/shared\/farmConfig.js'/);
assert.ok(!server.includes('const CROPS ='), 'server must not maintain a duplicate catalog');
console.log('PASS: shared farm configuration, preserved balance, validation and five-species products');
