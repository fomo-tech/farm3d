import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../src/game/world/FarmWorld.js', import.meta.url), 'utf8');
const start = source.indexOf('const cached = [...this.farmChunks.values()]');
const end = source.indexOf("\n        }\n        window.__farmDebug", start);
const trim = new Function('selected', 'player', source.slice(start, end));
const chunks = Array.from({ length: 12 }, (_, i) => ({ farmId: `farm-${i}`, farm: { x: i, z: 0 }, detailReady: i !== 0, buildingInProgress: i === 0, wantsDetail: i >= 8, lastUsed: i }));
let victim;
const world = { isMobile: true, farmChunks: new Map(chunks.map(c => [c.farmId, c])), playerFarmId: 'own', evictFarmCache(c) { victim = c; } };
trim.call(world, new Set(['farm-8', 'farm-9', 'farm-10', 'farm-11']), { root: { position: { x: 0, z: 0 } } });
assert.equal(victim, chunks[0], 'obsolete partial construction must be evicted even within 260m');
victim = null;
world.isMobile = false;
trim.call(world, new Set(), { root: { position: { x: 0, z: 0 } } });
assert.equal(victim, null, 'desktop keeps its distance policy');
const methodStart = source.indexOf('  evictFarmCache(chunk) {');
const methodEnd = source.indexOf('\n  ensurePlayerHome()', methodStart);
const method = source.slice(methodStart, methodEnd);
const evict = new Function('chunk', method.slice(method.indexOf('{') + 1, method.lastIndexOf('}')));
const cancelled = [];
let priority;
const chunk = { farmId: 'old', gatePending: true };
evict.call({ isMobile: true, scheduler: { cancel(id) { cancelled.push(id); }, enqueue(task, rank) { priority = rank; } } }, chunk);
assert.deepEqual(cancelled, ['farm-build-old', 'farm-gate-old', 'farm-buildings-old']);
assert.equal(chunk.gatePending, false);
assert.ok(priority > 10, 'cleanup must run before detail construction');
console.log('PASS: mobile releases cold/partial farm cache nearby and prioritizes cleanup over construction');
