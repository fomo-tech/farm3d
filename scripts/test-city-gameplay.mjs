import assert from 'node:assert/strict';
import {applyCityAction,CITY_GARAGE,CITY_CONTRACTS} from '../shared/cityGameplay.js';
import {stepCityDriving} from '../src/game/player/cityDriving.js';
import {createCityCollision} from '../server/CityWorldPolicy.js';
const p={coins:180,xp:0,vehicle:'walk',ownedVehicles:['walk']};
const context={worldMode:'city',...CITY_GARAGE};
assert.throws(()=>applyCityAction(p,'city_enter',{},{}));
applyCityAction(p,'city_enter',{},context,0);
assert.ok(p.ownedVehicles.includes('convertible'));
assert.throws(()=>applyCityAction(p,'city_vehicle',{}, {...context,x:999}));
applyCityAction(p,'city_vehicle',{},context,0);assert.equal(p.vehicle,'convertible');
const job=CITY_CONTRACTS.find(j=>j.id==='south-delivery');applyCityAction(p,'city_contract_start',{id:job.id},context,0);
assert.throws(()=>applyCityAction(p,'city_contract_start',{id:job.id},context,0));
assert.throws(()=>applyCityAction(p,'city_contract_finish',{},context,100000));
assert.throws(()=>applyCityAction(p,'city_contract_finish',{}, {...context,...job.target},1));
applyCityAction(p,'city_contract_finish',{}, {...context,...job.target},100000);
assert.equal(p.coins,180+job.reward);assert.equal(p.xp,job.xp);
assert.throws(()=>applyCityAction(p,'city_contract_finish',{}, {...context,...job.target},100001));
applyCityAction(p,'city_vehicle',{}, {...context,...job.target},100002);assert.equal(p.vehicle,'walk');assert.deepEqual(p.city.carPosition,job.target);
let motion={speed:0,yaw:0};for(let i=0;i<60;i++)motion=stepCityDriving(motion.speed,motion.yaw,1,0,false,1/60);
assert.ok(motion.speed>0&&motion.speed<=18);assert.equal(motion.yaw,0);
assert.ok(stepCityDriving(motion.speed,0,1,1,false,.1).yaw>0);
for(let i=0;i<60;i++)motion=stepCityDriving(motion.speed,motion.yaw,0,0,true,1/60);
assert.equal(motion.speed,0);assert.equal(stepCityDriving(0,0,0,1,false,.1).yaw,0);
assert.ok(stepCityDriving(0,0,-1,0,false,.1).speed<0);
const collision=createCityCollision();
assert.equal(collision.isColliding(CITY_GARAGE.x,CITY_GARAGE.z,1),false);
for(const j of CITY_CONTRACTS)assert.equal(collision.isColliding(j.target.x,j.target.z,1),false,j.id);
console.log('PASS city gameplay: proximity, delivery timing, single reward, persistence data, throttle/brake/reverse/steering and accessible destinations');
