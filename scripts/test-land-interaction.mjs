import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../src/game/farming/FarmingSystem.js',import.meta.url),'utf8');
const start=source.indexOf('    this.pointerHandler =');
const end=source.indexOf('    // A tap/click',start);
const controls={onLandInteract:()=>opened++,move:point=>moved.push(point),landAt:()=>({farmId:'farm_000001'})};
let opened=0;const moved=[];
const system={controls,interactTile:()=>interacted++};let interacted=0;
new Function(source.slice(start,end)).call(system);
const point={x:147,z:-70};
for(const mesh of [{metadata:{}},{metadata:{type:'farm-ground'}},{metadata:{type:'decoration'}}])system.pointerHandler({}, {pickedMesh:mesh,pickedPoint:point});
assert.equal(opened,0,'ground/decorations inside farm never open land office');
assert.equal(moved.length,3,'clicking farm ground remains movement');
controls.onLandInteract=id=>{assert.equal(id,'farm_000001');opened++;};
system.pointerHandler({}, {pickedMesh:{metadata:{type:'land-sign',farmId:'farm_000001'}},pickedPoint:point});
assert.equal(opened,1,'farm name board opens the selected parcel');
assert.equal(moved.length,3,'sign interaction does not also move');
system.pointerHandler({}, {pickedMesh:{metadata:{type:'farm-tile',interactive:true}},pickedPoint:point});
assert.equal(interacted,1);assert.equal(opened,1,'crop interaction never opens land office');
const world=readFileSync(new URL('../src/game/world/FarmWorld.js',import.meta.url),'utf8');
assert.ok(!world.includes('openNearbyLand()'),'proximity/keyboard cannot open a parcel without its sign');
console.log('PASS farm clicks: ground moves, only name sign opens parcel, crops remain interactive and proximity popup removed');
