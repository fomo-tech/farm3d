import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { TransformNode } from '@babylonjs/core/Meshes/transformNode.js';
import { MeshBuilder } from '@babylonjs/core/Meshes/meshBuilder.js';
import { Vector3 } from '@babylonjs/core/Maths/math.vector.js';
import { AssetContainer } from '@babylonjs/core/assetContainer.js';
import { modelWorldPosition, modelSubtreePredicate, attachVillageHouse } from '../src/game/rendering/ModelPlacement.js';
const engine = new NullEngine();
const scene = new Scene(engine);
const estate = new TransformNode('estate', scene);
estate.position.set(125, 0, -90);
const planter = new TransformNode('planter', scene);
planter.parent = estate;
planter.position.set(3, 0, 4);
planter.scaling.set(2, 1, 2);
const absolute = modelWorldPosition(new Vector3(1, 0, 1), planter);
assert.ok(absolute.equalsWithEpsilon(new Vector3(130, 0, -84)));
assert.ok(modelWorldPosition(Vector3.Zero(), estate).equalsWithEpsilon(estate.position));
const container = new AssetContainer(scene);
const root = new TransformNode('village-root', scene);
root.scaling.z = -1; // glTF handedness conversion must survive reparenting.
const house1 = MeshBuilder.CreateBox('house1', {}, scene);
const house10 = MeshBuilder.CreateBox('house10', {}, scene);
const roof = MeshBuilder.CreateBox('roof', {}, scene);
house1.parent = root; house10.parent = root; roof.parent = house1;
container.transformNodes = [root];
container.meshes = [house1, house10, roof];
const predicate = modelSubtreePredicate(container, 'house1');
assert.equal(predicate(root), true);
assert.equal(predicate(house1), true);
assert.equal(predicate(roof), true);
assert.equal(predicate(house10), false, 'house1 must not select house10');
const instance = container.instantiateModelsToScene(name => `${name}_test`, false, { predicate });
const names = instance.rootNodes.flatMap(node => node.getChildMeshes().map(mesh => mesh.name));
assert.ok(names.includes('house1_test'));
assert.ok(names.includes('roof_test'));
assert.ok(!names.includes('house10_test'));
const loadedHouse = instance.rootNodes[0].getChildMeshes().find(mesh => mesh.name === 'house1_test');
loadedHouse.name = 'house1_inst_test';
loadedHouse.position.set(20, 0, 20);
loadedHouse.freezeWorldMatrix();
const attached = attachVillageHouse(estate, instance, 'house1');
assert.equal(attached, loadedHouse);
assert.ok(attached.getAbsolutePosition().equalsWithEpsilon(estate.position), 'frozen GLB pose must be recomputed after reparenting');
assert.ok(attached.getWorldMatrix().determinant() < 0, 'preserve glTF handedness, so faces do not disappear');
assert.ok(instance.rootNodes.includes(attached), 'reparented mesh remains owned by disposable instance');
instance.dispose();
assert.equal(attached.isDisposed(), true);
scene.dispose(); engine.dispose();
console.log('PASS: nested world coordinates and exact village subtree instantiation preserve requested mesh without unrelated houses');
