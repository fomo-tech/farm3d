world.player={root:{position:new Vector3(0,0,0)},stop(){},lookAt(){},playAction(type,callback){assert.equal(type,'feed');animations++;hit=callback;}};
world.farmBuildings=new Map([['farm',{herd:{members:new Map([['hen',{root,species:'chicken'}]])}}]]);
world.callbacks={onLivestockInteract(){}};
world.moveToTarget=(destination,callback)=>{assert.equal(destination.z,.09999999999999998);arrival=callback;return true;};
const target={farmId:'farm',id:'hen',species:'chicken'};
world.performLivestockInteraction(target,'feed_animals',target,()=>{sends++;return true;});
assert.equal(sends,0);assert.equal(animations,0);
world.performLivestockInteraction(target,'feed_animals',target,()=>{sends++;return true;});
arrival();assert.equal(animations,1);assert.equal(sends,0);
await hit();await hit();assert.equal(sends,1);
