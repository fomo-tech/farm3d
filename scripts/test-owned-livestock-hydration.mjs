import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {NullEngine} from '@babylonjs/core/Engines/nullEngine.js';
import {Scene} from '@babylonjs/core/scene.js';
import {TransformNode} from '@babylonjs/core/Meshes/transformNode.js';
import {OwnedHerd} from '../src/game/livestock/OwnedHerd.js';
const source=readFileSync('src/game/world/FarmWorld.js','utf8');
const method=source.slice(source.indexOf('  syncOwnedLivestock('),source.indexOf('  applyPublicFarmScope('));
const World=new Function(`return class {${method}}`)();
const w=new World(),e=new NullEngine(),s=new Scene(e),root=new TransformNode('corral',s);
w.playerFarmId='farm_000001';w.farmBuildings=new Map();w.farmChunks=new Map();w.callbacks={getPlayerName:()=> 'Nông dân'};
let requests=0;w.ensureDetailedFarm=()=>requests++;
const animals=[{id:'saved-purchase',species:'chicken',createdAt:Date.now(),lifeVersion:1}];
w.syncOwnedLivestock(animals,{chicken:true},w.playerFarmId);
assert.equal(w.ownedLivestock.animals,animals,'Account received before terrain remains retained');
const herd=new OwnedHerd(s,root);w.farmBuildings.set(w.playerFarmId,{herd});w.farmChunks.set(w.playerFarmId,{});
w.syncOwnedLivestock(animals,{chicken:true},w.playerFarmId);
assert.equal(herd.members.size,1);assert.ok(herd.members.get('saved-purchase').root.isEnabled());assert.equal(requests,1,'Ready world promotes owned chunk');
const app=readFileSync('src/App.jsx','utf8');
assert.ok(app.includes('[animals, progress.animalPens, session.farmId, boot.phase]'),'Hydrate again when world ready and after account updates');
herd.dispose();s.dispose();e.dispose();
console.log('PASS: account before world initialization, ready-world hydration, retained ownership and visible saved purchase');
