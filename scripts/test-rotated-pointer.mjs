import assert from 'node:assert/strict';
import { logicalPointer, installRotatedPointer } from '../src/game/input/rotatedPointer.js';
const rect={left:10,top:20,right:400,width:390,height:844};
assert.deepEqual(logicalPointer(400,20,rect,true),{x:0,y:0});
assert.deepEqual(logicalPointer(10,864,rect,true),{x:844,y:390});
assert.deepEqual(logicalPointer(205,442,rect,true),{x:422,y:195});
assert.deepEqual(logicalPointer(205,442,rect,false),{x:195,y:422});
let rotated=true, dispose;
globalThis.document={documentElement:{classList:{contains:()=>rotated}}};
const listeners=new Map();
const canvas={clientWidth:844,clientHeight:390,getBoundingClientRect:()=>rect,addEventListener:(t,f)=>listeners.set(t,f),removeEventListener:t=>listeners.delete(t)};
const engine={getInputElementClientRect:()=>rect,onDisposeObservable:{addOnce:f=>{dispose=f}}};
installRotatedPointer(engine,canvas);
const event={clientX:205,clientY:442}; listeners.get('pointermove')(event);
assert.equal(event.clientX,422);assert.equal(event.clientY,195);
assert.equal(engine.getInputElementClientRect().width,844);
rotated=false;assert.equal(engine.getInputElementClientRect(),rect);
dispose();assert.equal(listeners.size,0);
console.log('PASS: rotated pointer mapping, native orientation and listener disposal');
