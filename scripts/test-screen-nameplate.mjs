import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { TransformNode } from '@babylonjs/core/Meshes/transformNode.js';
import { ArcRotateCamera } from '@babylonjs/core/Cameras/arcRotateCamera.js';
import { Vector3 } from '@babylonjs/core/Maths/math.vector.js';
import { createScreenNameplate } from '../src/game/player/createScreenNameplate.js';
import { createPlayerNameplate } from '../src/game/player/createPlayerNameplate.js';
const labels = [];
const canvas = { parentElement: { appendChild(label) { labels.push(label); } }, getBoundingClientRect: () => ({ left:0, top:0, width:800, height:600 }) };
globalThis.document = { createElement: () => ({ style: {}, offsetWidth:100, offsetHeight:24, remove() { labels.splice(labels.indexOf(this), 1); } }) };
const engine = new NullEngine({ renderWidth:800, renderHeight:600 });
engine.getRenderingCanvas = () => canvas;
const scene = new Scene(engine);
new ArcRotateCamera('camera', -Math.PI/2, 1.1, 14, new Vector3(0,1.2,0), scene);
const root = new TransformNode('player', scene);
const plate = createScreenNameplate(scene, root, 'Nông dân mới');
scene.render();
scene.render();
assert.equal(labels[0].textContent, 'Nông dân mới');
assert.equal(labels[0].title, 'Bạn: Nông dân mới');
assert.equal(labels[0].hidden, false);
assert.match(labels[0].style.left, /^-?\d+px$/);
assert.equal(scene.textures.length, 0, 'screen text requires no low-resolution render texture');
root.setEnabled(false); scene.render(); assert.equal(labels[0].hidden, true);
plate.setName('<b>Tên</b>'); assert.equal(labels[0].textContent, '<b>Tên</b>');
const remoteRoot = new TransformNode('remote-player-test', scene);
const remotePlate = createPlayerNameplate(scene, remoteRoot, 'test', 'Nông dân mới');
assert.equal(remotePlate.mesh, null, 'remote players use sharp screen labels too');
scene.render();
assert.equal(labels[1].textContent, 'Nông dân mới');
assert.equal(labels[1].title, 'Người chơi khác: Nông dân mới');
assert.equal(labels[1].hidden, false);
assert.notEqual(labels[0].style.color, labels[1].style.color);
assert.match(labels[0].style.cssText, /background:transparent/);
assert.match(labels[1].style.cssText, /background:transparent/);
assert.notEqual(labels[0].className, labels[1].className);
root.setEnabled(true);
const nearFont = parseInt(labels[1].style.fontSize, 10);
scene.activeCamera.radius = 26; scene.render(); scene.render();
assert.ok(parseInt(labels[0].style.fontSize, 10) < nearFont, 'local name shrinks when zooming out');
assert.ok(parseInt(labels[1].style.fontSize, 10) < nearFont, 'remote name shrinks when zooming out');
scene.activeCamera.radius = 48; scene.render(); scene.render();
assert.equal(labels[0].hidden, true, 'hide unreadably small names at distant zoom');
scene.activeCamera.radius = 14; scene.render(); scene.render();
assert.equal(labels[0].hidden, false);
assert.equal(parseInt(labels[1].style.fontSize, 10), nearFont);
remoteRoot.position.z = 100; scene.render(); assert.equal(labels[1].hidden, true);
remoteRoot.position.z = 0; scene.render(); assert.equal(labels[1].hidden, false);
remoteRoot.setEnabled(false); scene.render(); assert.equal(labels[1].hidden, true);
scene.dispose(); assert.equal(labels.length, 0);
plate.dispose(); remotePlate.dispose(); delete globalThis.document; engine.getRenderingCanvas = () => null; engine.dispose();
console.log('PASS: readable screen text, integer placement, hidden parent, safe names and scene cleanup.');
