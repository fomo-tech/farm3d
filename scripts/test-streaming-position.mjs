import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { TransformNode } from '@babylonjs/core/Meshes/transformNode.js';
import { Vector3 } from '@babylonjs/core/Maths/math.vector.js';
import { streamingPosition } from '../src/game/world/streamingPosition.js';
const engine = new NullEngine();
const scene = new Scene(engine);
const parent = new TransformNode('parent', scene);
parent.position.set(300, 0, 400);
const player = new TransformNode('player', scene);
player.parent = parent;
player.position.set(5, 0, 7);
parent.computeWorldMatrix(true); player.computeWorldMatrix(true);
scene.metadata = { streamingPlayer: player };
scene.activeCamera = { target: new Vector3(-900, 0, -900) };
assert.equal(streamingPosition(scene).x, 305);
assert.equal(streamingPosition(scene).z, 407);
scene.metadata = {};
scene.activeCamera.lockedTarget = player;
assert.equal(streamingPosition(scene).x, 305, 'locked target uses world, not local coordinates');
scene.activeCamera = null;
scene.dispose(); engine.dispose();
console.log('PASS: authoritative player world position, camera orbit and parent transforms');
