import { FreeCamera } from '@babylonjs/core/Cameras/freeCamera.js';
import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { MeshBuilder } from '@babylonjs/core/Meshes/meshBuilder.js';
import { TransformNode } from '@babylonjs/core/Meshes/transformNode.js';
import { Vector3 } from '@babylonjs/core/Maths/math.vector.js';
import { Octree } from '@babylonjs/core/Culling/Octrees/octree.js';
import { installWorldRenderIndex } from '../src/game/rendering/WorldRenderIndex.js';
const engine = new NullEngine(), scene = new Scene(engine);
const shore = new TransformNode('river-shore-bushes', scene);
const bush = MeshBuilder.CreateBox('bush-leaves', {}, scene); bush.parent = shore;
const bridge = MeshBuilder.CreateBox('bridge-main-rail', {}, scene); bridge.parent = shore;
const wave = MeshBuilder.CreateBox('lake-wave', {}, scene); wave.metadata = { lakeStatic: false };
const fleet = new TransformNode('bus-01', scene);
const seat = MeshBuilder.CreateBox('seat', {}, scene); seat.parent = fleet;
const meshes = Array.from({length: 180}, (_, i) => {
  const mesh = MeshBuilder.CreateBox(`house-${i}`, {}, scene);
  mesh.position.set(i < 90 ? 110 : 800, 10, 110); mesh.computeWorldMatrix(true); return mesh;
});
const legacy = new Octree(Octree.CreationFuncForMeshes,64,2);
legacy.update(new Vector3(-4096,-512,-4096),new Vector3(4096,512,4096),meshes);
const before = legacy.intersects(new Vector3(110,10,110),5).length;
const index = installWorldRenderIndex(scene); await index.ready;
assert.ok(!scene.selectionOctree.dynamicContent.includes(bush), 'bush is not a bus; material-animated river parent is static');
assert.ok(!scene.selectionOctree.dynamicContent.includes(bridge));
assert.ok(scene.selectionOctree.dynamicContent.includes(wave), 'moving lake bounds remain dynamic');
assert.ok(scene.selectionOctree.dynamicContent.includes(seat), 'bus passenger frame remains dynamic');
const selected = scene.selectionOctree.intersects(new Vector3(110,10,110),5);
const selectedMeshes = new Set(selected.data.slice(0,selected.length));
assert.ok(meshes.slice(0,90).every(mesh => selectedMeshes.has(mesh)), 'all nearby geometry remains visible');
assert.ok(meshes.slice(90).every(mesh => !selectedMeshes.has(mesh)), 'distant geometry is excluded before per-mesh evaluation');
assert.ok(selected.length < before);
console.log(`PASS: bush/river static bounds, bus/lake animation, finer spatial selection ${before} -> ${selected.length} candidates`);
const camera = new FreeCamera('camera', new Vector3(0, 4, -10), scene);
camera.setTarget(Vector3.Zero());
scene.render();
fleet.setEnabled(false);
let candidates = scene.getActiveMeshCandidates();
assert.ok(!candidates.data.slice(0,candidates.length).includes(seat), 'disabled avatar/vehicle parent is excluded before LOD evaluation');
fleet.setEnabled(true);
candidates = scene.getActiveMeshCandidates();
assert.ok(candidates.data.slice(0,candidates.length).includes(seat), 're-enabled wardrobe/vehicle returns without rebuilding index');
index.dispose(); scene.dispose(); engine.dispose();
