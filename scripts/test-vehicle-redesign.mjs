import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { Scene } from '@babylonjs/core/scene.js';
import { TransformNode } from '@babylonjs/core/Meshes/transformNode.js';
import { VEHICLES } from '../shared/vehicleConfig.js';
import { createVehiclePanel } from '../src/game/player/createVehiclePanel.js';
import { createVehicleRigs } from '../src/game/player/createVehicleRigs.js';
assert.deepEqual(['bike','scooter','tractor','kart','convertible','hoverboard','skateboard'].map(id => [VEHICLES[id].cost, VEHICLES[id].speed]), [[350,10],[900,14],[2200,18],[1500,16],[3200,18],[2600,15],[200,9]], 'redesign preserves balance and saved IDs');
const engine = new NullEngine(), scene = new Scene(engine);
const panel = createVehiclePanel(scene, 'test-panel', 1.8, .48, 2.9);
assert.equal(panel.getTotalVertices(), 34, 'low-cost chamfered body');
const normals = panel.getVerticesData('normal');
assert.ok(normals[32*3+1] < -.99, 'bottom points out');
assert.ok(normals[33*3+1] > .99, 'top points out');
panel.dispose();
const root = new TransformNode('test', scene), rigs = createVehicleRigs(scene, root);
rigs.setVehicle('bike');
assert.ok(scene.getMeshByName('bike-trail-frame-0'));
assert.ok(!scene.meshes.some(mesh => /basket|flw/.test(mesh.name)), 'no flower basket');
rigs.setVehicle('convertible');
assert.equal(scene.getMeshByName('convertible-lower-body').getTotalVertices(), 34);
assert.ok(scene.getMeshByName('convertible-front-grille'));
assert.ok(scene.materials.every(material => material.emissiveColor.asArray().every(value => value <= .05)), 'no excessive emission');
rigs.dispose(); scene.dispose(); engine.dispose();
console.log('PASS: urban/trail geometry, chamfer normals, restrained materials, preserved prices/speeds/IDs');
